"""
Bit-exact integer golden model for the BitMamba-CV RTL (article/hw/rtl).

This file is the single numerical specification of the hardware. Every RTL module
listed below is checked against it by article/hw/tb (vectors generated by
article/sw/gen_tb_vectors.py, 0 mismatches required):

  radix3_decoder.v       <- RADIX3_LUT
  fwht16.v               <- fwht16_int
  bitlinear_engine.v     <- matvec_int (ENC=TERN2 / RADIX3 / INT8)
  scan_lane.v            <- scan_lane_run (DECAY=CPOT or MULT)

All arithmetic is plain Python/NumPy integers (int64), arithmetic shifts are floor
shifts (same as Verilog >>> on signed values).
"""

from __future__ import annotations
from dataclasses import dataclass
import numpy as np


# ------------------------------------------------------------------------------
# 1. Radix-3 packing: 5 trits {-1,0,+1} -> 1 byte in [0, 242] (1.6 bit/weight)
# ------------------------------------------------------------------------------

POW3 = np.array([1, 3, 9, 27, 81], dtype=np.int64)


def pack_radix3(w: np.ndarray) -> np.ndarray:
    """Packs a flat ternary array (len multiple of 5) into uint8 bytes."""
    w = np.asarray(w, dtype=np.int64).reshape(-1, 5)
    assert np.all(np.abs(w) <= 1)
    return ((w + 1) * POW3).sum(axis=1).astype(np.uint8)


def build_radix3_lut() -> np.ndarray:
    """256x5 table; codes 243..255 are invalid and decode to zeros (as in RTL)."""
    lut = np.zeros((256, 5), dtype=np.int64)
    for b in range(243):
        v = b
        for i in range(5):
            lut[b, i] = v % 3 - 1
            v //= 3
    return lut


RADIX3_LUT = build_radix3_lut()


def unpack_radix3(packed: np.ndarray) -> np.ndarray:
    return RADIX3_LUT[np.asarray(packed, dtype=np.int64)].reshape(-1)


def radix3_memory_words(w_rows: np.ndarray) -> np.ndarray:
    """
    Memory image used by bitlinear_engine (ENC=RADIX3): rows of P trits are grouped
    5 at a time; 5 rows = 5P trits = P bytes = one 8P-bit word.
    Returns uint8 array (n_words, P); byte i of word -> bits [8i+7:8i].
    """
    n_rows, P = w_rows.shape
    pad = (-n_rows) % 5
    w = np.concatenate([w_rows, np.zeros((pad, P), dtype=w_rows.dtype)])
    return pack_radix3(w.reshape(-1)).reshape(-1, P)


# ------------------------------------------------------------------------------
# 2. 16-point Fast Walsh-Hadamard Transform (exact, unnormalized)
# ------------------------------------------------------------------------------

def fwht16_int(x: np.ndarray) -> np.ndarray:
    """
    Exact integer H16 @ x on the last axis (blocks of 16). INT8 in -> 12-bit out
    (|y| <= 16*128 = 2048). The 1/4 normalisation is not applied here: it is folded
    into the per-token requantisation scale that follows the transform.
    """
    x = np.asarray(x, dtype=np.int64)
    h = x.reshape(-1, 16).copy()
    stride = 1
    while stride < 16:
        h = h.reshape(-1, 16 // (2 * stride), 2, stride)
        a, b = h[:, :, 0, :], h[:, :, 1, :]
        h = np.stack([a + b, a - b], axis=2).reshape(-1, 16)
        stride *= 2
    return h.reshape(x.shape)


# ------------------------------------------------------------------------------
# 3. BitLinear / INT8 matrix-vector engine
# ------------------------------------------------------------------------------

def matvec_int(w: np.ndarray, x: np.ndarray) -> np.ndarray:
    """y[m] = sum_k w[m,k] * x[k] in int64 (RTL accumulator is wide enough)."""
    return np.asarray(w, dtype=np.int64) @ np.asarray(x, dtype=np.int64)


# ------------------------------------------------------------------------------
# 4. Selective-scan lane (one channel, N states) - Mamba-2 recurrence
#    h_t = Abar_t * h_{t-1} + Delta_t * (x_t * B_t)
#    y_t = sum_n C_t[n] * h_t[n]
# ------------------------------------------------------------------------------

@dataclass(frozen=True)
class ScanCfg:
    state_w: int = 32      # state register width (bits, signed, saturating)
    guard: int = 10        # extra fractional bits of the state w.r.t. B*x
    round_shift: bool = True  # round-to-nearest in the CPoT shift (else floor)
    decay: str = "cpot"    # "cpot": shift/sub  | "mult": Q1.15 multiplier
    y_w: int = 24          # output width (saturating)


LEGACY_16 = ScanCfg(state_w=16, guard=0, round_shift=False)  # original design
PROPOSED_32 = ScanCfg()                                        # corrected design
MULT_Q15 = ScanCfg(decay="mult")                               # DSP baseline


def _sat(v: np.ndarray, bits: int) -> np.ndarray:
    lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    return np.clip(v, lo, hi)


def _shr(v: np.ndarray, k: np.ndarray, rnd: bool) -> np.ndarray:
    v = np.asarray(v, dtype=np.int64)
    k = np.asarray(k, dtype=np.int64)
    if rnd:
        v = v + np.where(k > 0, np.left_shift(1, np.maximum(k - 1, 0)), 0)
    return np.right_shift(v, k)


def scan_lane_step(h, x, b, c, m, k, j, a_q15, cfg: ScanCfg):
    """
    One token. Shapes broadcast: h,b,c (..., N); x,m,k,j,a_q15 (...,1) or scalars.
      x, b, c : int8
      m, k    : CPoT code (m=0 -> 2^-k, m=1 -> 1-2^-k), k in [0, 15]
      j       : Delta = 2^-j (power-of-two step), j in [0, 15]
      a_q15   : Abar in Q1.15 (only used when cfg.decay == "mult")
    Returns (h_new, y) with y = sat_{y_w}( sum_n h_new*c >>> guard ).
    """
    h = np.asarray(h, dtype=np.int64)
    if cfg.decay == "cpot":
        s = _shr(h, k, cfg.round_shift)
        h_dec = np.where(np.asarray(m) == 1, h - s, s)
    else:
        h_dec = np.right_shift(h * np.asarray(a_q15, dtype=np.int64) + (1 << 14), 15)
    bx = np.asarray(b, dtype=np.int64) * np.asarray(x, dtype=np.int64)
    inj = np.right_shift(np.left_shift(bx, cfg.guard), np.asarray(j, dtype=np.int64))
    h_new = _sat(h_dec + inj, cfg.state_w)
    acc = np.sum(h_new * np.asarray(c, dtype=np.int64), axis=-1)
    y = _sat(np.right_shift(acc, cfg.guard), cfg.y_w)
    return h_new, y


def scan_lane_run(x, b, c, m, k, j, a_q15, cfg: ScanCfg):
    """Runs a whole sequence (time on axis 0). Returns y (T,)."""
    N = b.shape[1]
    h = np.zeros(N, dtype=np.int64)
    ys = []
    for t in range(len(x)):
        h, y = scan_lane_step(h, x[t], b[t], c[t], m[t], k[t], j[t], a_q15[t], cfg)
        ys.append(int(y))
    return np.array(ys, dtype=np.int64)


# ------------------------------------------------------------------------------
# 5. Encoders float -> hardware codes (used by QAT emulation and TB generation)
# ------------------------------------------------------------------------------

CPOT_THRESHOLD = 0.625


def encode_cpot(abar: np.ndarray, k_max: int = 15):
    """Abar in (0,1) -> (m, k): nearest level in the log domain of each branch."""
    a = np.clip(abar, 1e-9, 1 - 1e-9)
    m = (a > CPOT_THRESHOLD).astype(np.int64)
    k_lo = np.clip(np.round(-np.log2(a)), 1, k_max)
    k_hi = np.clip(np.round(-np.log2(1 - a)), 1, k_max)
    return m, np.where(m == 1, k_hi, k_lo).astype(np.int64)


def decode_cpot(m, k):
    return np.where(m == 1, 1.0 - 2.0 ** -k, 2.0 ** -k)


def encode_pot_delta(dt: np.ndarray, j_max: int = 15) -> np.ndarray:
    return np.clip(np.round(-np.log2(np.clip(dt, 1e-9, None))), 0, j_max).astype(np.int64)


